// Builds the MCP App pages: bundles each page's TypeScript and inlines it, with its CSS, into one
// self-contained HTML file, written as a checked-in module (src/mcp/app/generated.ts) so `heph mcp`
// needs no runtime files. `bun run build:apps` regenerates; a test fails when the file is stale.
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const app = join(root, "src/mcp/app");
export const GENERATED = join(app, "generated.ts");

async function buildPage(entry: string, template: string): Promise<string> {
  const out = await Bun.build({
    entrypoints: [join(app, entry)],
    target: "browser",
    format: "iife",
    minify: true,
  });
  if (!out.success) throw new Error(`build ${entry} failed:\n${out.logs.join("\n")}`);
  const js = (await out.outputs[0]?.text()) ?? "";
  // Nothing in the script may end the inline <script> block early.
  const safe = js
    .trim()
    .replace(/<\/(script)/gi, "<\\/$1")
    .replace(/<!--/g, "<\\!--");
  const html = await Bun.file(join(app, template)).text();
  return html.replace("/*SCRIPT*/", () => safe);
}

export const buildPlanHtml = () => buildPage("plan-main.ts", "plan.html");

export async function generatedSource(): Promise<string> {
  return `// Generated by packages/cli/scripts/build-apps.ts (bun run build:apps). Do not edit.\nexport const PLAN_HTML = ${JSON.stringify(await buildPlanHtml())};\n`;
}

if (import.meta.main) {
  await Bun.write(GENERATED, await generatedSource());
  console.log(`wrote ${GENERATED}`);
}
